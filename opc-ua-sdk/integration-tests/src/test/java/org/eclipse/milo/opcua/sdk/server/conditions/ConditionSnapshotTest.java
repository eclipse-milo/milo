  @Test
  void capturedAlarmRoundTripsThroughRestoreWithRefreshReplayAndAcknowledge() throws Exception {
    var subscription = new OpcUaSubscription(client);
    subscription.create();

    try {
      List<Variant[]> events =
          EventTestSupport.monitorEvents(subscription, NodeIds.Server, severityFilter());

      // Drive the original alarm into an active/unacked/commented/shelved state.
      originalAlarm.evaluate(92.0);
      originalAlarm.setComment(LocalizedText.english("operator note"), "operator1");

      CallMethodResult shelve =
          call(
              requireNonNull(originalAlarm.getShelvingState()).getNodeId(),
              NodeIds.ShelvedStateMachineType_TimedShelve,
              new Variant(60_000.0));
      assertGood(shelve);
      EventTestSupport.awaitEvent(
          events, "TimedShelved event", e -> "TimedShelved".equals(messageOf(e)));

      ConditionSnapshot snapshot = originalAlarm.captureSnapshot();
      ByteString originalEventId = originalAlarm.currentBranch().getLastEventId();
      DateTime originalEventTime = originalAlarm.currentBranch().getLastEventTime();

      // The captured shape carries the condition, shelving, and branch state.
      assertEquals(Boolean.TRUE, snapshot.enabled());
      assertEquals(LocalizedText.english("operator note"), snapshot.comment());
      assertEquals("operator1", snapshot.clientUserId());
      ConditionSnapshot.ShelvingSnapshot shelving = requireNonNull(snapshot.shelving());
      assertEquals(ShelvedState.TIMED_SHELVED, shelving.state());
      assertNotNull(shelving.unshelveDeadline());
      ConditionSnapshot.BranchSnapshot trunk = snapshot.trunk().orElseThrow();
      assertEquals(Boolean.FALSE, trunk.acked());
      assertEquals(Boolean.TRUE, trunk.active());
      assertEquals(Set.of(ExclusiveLimitState.HIGH), trunk.activeLimits());
      assertEquals(ExclusiveLimitState.HIGH, trunk.effectiveLimitState());
      assertTrue(trunk.retained());
      assertEquals(originalEventId, trunk.lastEventId());
      assertEquals(originalEventTime, trunk.lastEventTime());

      // "Restart": the original disappears; a fresh, identically configured instance restores.
      server.getConditionManager().unregister(originalAlarm);

      ExclusiveLevelAlarm restored =
          ExclusiveLevelAlarm.create(
              nodeContext,
              b ->
                  b.nodeId(newNodeId("ConditionSnapshotTest/Restored"))
                      .browseName(newQualifiedName("SnapshotRestored"))
                      .conditionSource(source)
                      .severity(ushort(TEST_SEVERITY))
                      .withConfirm()
                      .withShelving(Duration.ofMillis((long) MAX_TIME_SHELVED_MILLIS))
                      .highLimit(90.0)
                      .highHighLimit(95.0));

      restored.restoreSnapshot(snapshot);
      server.getConditionManager().register(restored);

      assertTrue(restored.isActive());
      assertEquals(ExclusiveLimitState.HIGH, restored.getLimitState());
      assertFalse(restored.isAcked());
      assertTrue(restored.isConfirmed());
      assertTrue(restored.isRetained());
      assertEquals("TimedShelved", currentStateText(restored));
      assertEquals(Boolean.TRUE, restored.getNode().getSuppressedOrShelved());
      assertEquals(LocalizedText.english("operator note"), restored.getNode().getComment());
      assertEquals("operator1", restored.getNode().getClientUserId());
      assertEquals(originalEventId, restored.currentBranch().getLastEventId());
      assertEquals(originalEventTime, restored.currentBranch().getLastEventTime());

      events.clear();

      // A reconnecting client learns the recovered state via refresh replay of the restored
      // branch, carrying the pre-capture EventId/Time and the restored instance's ConditionId.
      assertGood(conditionRefresh(subscription));

      Variant[] replay =
          EventTestSupport.awaitEvent(
              events, "restored branch replay", e -> originalEventId.equals(eventIdOf(e)));
      assertEquals(originalEventTime, replay[4].value(), "replay must carry the original Time");
      assertTrue(retainOf(replay));
      assertEquals(restored.getConditionId(), conditionIdOf(replay));

      // The pre-capture EventId is accepted by Acknowledge, which opens the confirm cycle.
      CallMethodResult acknowledge =
          call(
              restored.getConditionId(),
              NodeIds.AcknowledgeableConditionType_Acknowledge,
              new Variant(originalEventId),
              new Variant(LocalizedText.english("ack after restore")));
      assertGood(acknowledge);
      assertTrue(restored.isAcked());
      assertFalse(restored.isConfirmed());
    } finally {
      subscription.delete();
    }
  }

  // A caller-selected effective state is part of the reduced alarm state; losing it on restart
  // would silently change the alarm's classification, severity, and operator-facing text.
  @Test
  void callerSelectedNonExclusiveEffectiveStateRoundTripsWithoutChangingBranchIdentity()
      throws Exception {

    NonExclusiveLimitAlarm original = createCrossSideAlarm("EffectiveOriginal");
    original.setLimitStates(
        Set.of(ExclusiveLimitState.HIGH, ExclusiveLimitState.LOW), ExclusiveLimitState.LOW);

    ConditionSnapshot snapshot = original.captureSnapshot();
    ConditionSnapshot.BranchSnapshot captured = snapshot.trunk().orElseThrow();
    ByteString capturedEventId = requireNonNull(captured.lastEventId());
    DateTime capturedEventTime = requireNonNull(captured.lastEventTime());

    assertEquals(
        Set.of(ExclusiveLimitState.HIGH, ExclusiveLimitState.LOW), captured.activeLimits());
    assertEquals(ExclusiveLimitState.LOW, captured.effectiveLimitState());
    assertTrue(capturedEventId.isNotNull());

    NonExclusiveLimitAlarm restored = createCrossSideAlarm("EffectiveRestored");
    var subscription = new OpcUaSubscription(client);
    subscription.create();
    try {
      List<Variant[]> events =
          EventTestSupport.monitorEvents(
              subscription, NodeIds.Server, conditionNameFilter("EffectiveRestored"));

      restored.restoreSnapshot(snapshot);

      EventTestSupport.assertNoEvent(events, "event generated by non-exclusive restore", e -> true);
    } finally {
      subscription.delete();
    }

    assertTrue(restored.isActive());
    assertTrue(restored.isLimitActive(ExclusiveLimitState.HIGH));
    assertTrue(restored.isLimitActive(ExclusiveLimitState.LOW));
    assertEquals(ExclusiveLimitState.LOW, restored.getEffectiveLimitState());
    assertEquals(LocalizedText.english("Active/Low"), restored.getNode().getMessage());
    assertEquals(
        LocalizedText.english("Active/Low"),
        requireNonNull(restored.getNode().getActiveStateNode()).getEffectiveDisplayName());
    assertEquals(ushort(300), restored.getNode().getSeverity());
    assertEquals(ushort(100), restored.getNode().getLastSeverity());
    assertTrue(restored.isRetained());
    assertEquals(capturedEventId, restored.currentBranch().getLastEventId());
    assertEquals(capturedEventTime, restored.currentBranch().getLastEventTime());
    assertTrue(restored.currentBranch().isAcknowledgeable(capturedEventId));

    ConditionSnapshot.BranchSnapshot recaptured = restored.captureSnapshot().trunk().orElseThrow();
    assertEquals(captured.activeLimits(), recaptured.activeLimits());
    assertEquals(captured.effectiveLimitState(), recaptured.effectiveLimitState());
    assertEquals(captured.retained(), recaptured.retained());
    assertEquals(captured.eventIdWindow(), recaptured.eventIdWindow());
    assertEquals(capturedEventId, recaptured.lastEventId());
    assertEquals(capturedEventTime, recaptured.lastEventTime());
  }

