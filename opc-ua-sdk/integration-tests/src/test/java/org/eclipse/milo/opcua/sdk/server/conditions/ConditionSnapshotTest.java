  private static final int TEST_SEVERITY = 613;

  /** MaxTimeShelved configured on the shelvable alarms, in milliseconds. */
  private static final double MAX_TIME_SHELVED_MILLIS = 300_000.0;

  private UaNodeContext nodeContext;
  private UaObjectNode source;
  private ExclusiveLevelAlarm originalAlarm;

