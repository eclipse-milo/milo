/**
 * Node implementation of {@link AddressSpaceFileType}.
 *
 * @see <a href="https://reference.opcfoundation.org/v105/Core/docs/Part5/6.3.12">Model
 *     documentation</a>
 */
public class AddressSpaceFileTypeNode extends FileTypeNode implements AddressSpaceFileType {
  public AddressSpaceFileTypeNode(
      OpcUaClient client,
      NodeId nodeId,
      NodeClass nodeClass,
      QualifiedName browseName,
      LocalizedText displayName,
      @Nullable LocalizedText description,
      UInteger writeMask,
      UInteger userWriteMask,
      RolePermissionType @Nullable [] rolePermissions,
      RolePermissionType @Nullable [] userRolePermissions,
      @Nullable AccessRestrictionType accessRestrictions,
      UByte eventNotifier) {
    super(
        client,
        nodeId,
        nodeClass,
        browseName,
        displayName,
        description,
        writeMask,
        userWriteMask,
        rolePermissions,
        userRolePermissions,
        accessRestrictions,
        eventNotifier);
  }

  @Override
  public @Nullable UaMethodNode getExportNamespaceMethodNode() throws UaException {
    return ClientNodeSupport.await(getExportNamespaceMethodNodeAsync());
  }

  @Override
  public CompletableFuture<@Nullable UaMethodNode> getExportNamespaceMethodNodeAsync() {
    return ClientNodeSupport.defer(
        () ->
            ClientNodeSupport.optionalChild(
                client,
                this,
                "http://opcfoundation.org/UA/",
                "ExportNamespace",
                ExpandedNodeId.of(Namespaces.OPC_UA, 47L),
                NodeClass.Method,
                UaMethodNode.class));
  }

  @Override
  public void exportNamespace() throws UaException {
    ClientNodeSupport.await(exportNamespaceAsync());
  }

  @Override
  public MethodCallResult<Void> callExportNamespace() throws UaException {
    return ClientNodeSupport.await(callExportNamespaceAsync());
  }

  @Override
  public MethodCallResult<Void> callExportNamespaceWith(MethodCallOptions options)
      throws UaException {
    return ClientNodeSupport.await(callExportNamespaceWithAsync(options));
  }

  @Override
  public CompletableFuture<Void> exportNamespaceAsync() {
    return ClientNodeSupport.compose(
        callExportNamespaceAsync(),
        result ->
            ClientNodeSupport.defer(() -> CompletableFuture.completedFuture(result.requireGood())));
  }

  @Override
  public CompletableFuture<MethodCallResult<Void>> callExportNamespaceAsync() {
    return callExportNamespaceWithAsync(MethodCallOptions.DEFAULT);
  }

  @Override
  public CompletableFuture<MethodCallResult<Void>> callExportNamespaceWithAsync(
      MethodCallOptions options) {
    return ClientNodeSupport.defer(
        () -> {
          Variant[] inputs = new Variant[0];
          Variant[] suppliedInputs = inputs;
          return ClientNodeSupport.compose(
              getExportNamespaceMethodNodeAsync(),
              node ->
                  ClientNodeSupport.compose(
                      ClientNodeSupport.call(client, this, node, suppliedInputs, options),
                      result ->
                          CompletableFuture.completedFuture(
                              result.map(
                                  values -> {
                                    if (values == null || values.length != 0)
                                      throw new UaException(
                                          StatusCodes.Bad_DecodingError,
                                          "expected no Method outputs");
                                    return null;
                                  }))));
        });
  }
}
