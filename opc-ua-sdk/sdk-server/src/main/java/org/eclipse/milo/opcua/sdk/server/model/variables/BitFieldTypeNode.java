/**
 * Node implementation of {@link BitFieldType}.
 *
 * @see <a href="https://reference.opcfoundation.org/v105/Core/docs/Part5/7.29">Model
 *     documentation</a>
 */
public class BitFieldTypeNode extends BaseDataVariableTypeNode implements BitFieldType {
  public BitFieldTypeNode(
      UaNodeContext context,
      NodeId nodeId,
      QualifiedName browseName,
      LocalizedText displayName,
      @Nullable LocalizedText description,
      UInteger writeMask,
      UInteger userWriteMask,
      RolePermissionType @Nullable [] rolePermissions,
      RolePermissionType @Nullable [] userRolePermissions,
      @Nullable AccessRestrictionType accessRestrictions,
      DataValue value,
      NodeId dataType,
      Integer valueRank,
      UInteger @Nullable [] arrayDimensions) {
    super(
        context,
        nodeId,
        browseName,
        displayName,
        description,
        writeMask,
        userWriteMask,
        rolePermissions,
        userRolePermissions,
        accessRestrictions,
        value,
        dataType,
        valueRank,
        arrayDimensions);
  }

  public BitFieldTypeNode(
      UaNodeContext context,
      NodeId nodeId,
      QualifiedName browseName,
      LocalizedText displayName,
      @Nullable LocalizedText description,
      UInteger writeMask,
      UInteger userWriteMask,
      RolePermissionType @Nullable [] rolePermissions,
      RolePermissionType @Nullable [] userRolePermissions,
      @Nullable AccessRestrictionType accessRestrictions,
      DataValue value,
      NodeId dataType,
      Integer valueRank,
      UInteger @Nullable [] arrayDimensions,
      UByte accessLevel,
      UByte userAccessLevel,
      Double minimumSamplingInterval,
      boolean historizing,
      AccessLevelExType accessLevelEx) {
    super(
        context,
        nodeId,
        browseName,
        displayName,
        description,
        writeMask,
        userWriteMask,
        rolePermissions,
        userRolePermissions,
        accessRestrictions,
        value,
        dataType,
        valueRank,
        arrayDimensions,
        accessLevel,
        userAccessLevel,
        minimumSamplingInterval,
        historizing,
        accessLevelEx);
  }

  @Override
  public PropertyTypeNode getBitFieldsDefinitionsNode() {
    return ServerNodeSupport.mandatoryChild(
        this,
        Namespaces.OPC_UA,
        "BitFieldsDefinitions",
        ExpandedNodeId.of(Namespaces.OPC_UA, 46L),
        ExpandedNodeId.of(Namespaces.OPC_UA, 68L),
        ExpandedNodeId.of(Namespaces.OPC_UA, 32421L),
        1,
        PropertyTypeNode.class);
  }

  @Override
  public @Nullable BitFieldDefinition @Nullable [] getBitFieldsDefinitions() {
    return ServerNodeSupport.readArray(
        this, getBitFieldsDefinitionsNode(), BitFieldDefinition.class, null);
  }

  @Override
  public void setBitFieldsDefinitions(@Nullable BitFieldDefinition @Nullable [] value) {
    ServerNodeSupport.write(this, getBitFieldsDefinitionsNode(), value, true, false, true);
  }

  @Override
  public void validateChildren() {
    super.validateChildren();
    getBitFieldsDefinitionsNode();
  }

  @Override
  public @Nullable Variant getTypedValue() {
    return ServerNodeSupport.read(this, this, Variant.class, null);
  }

  @Override
  public void setTypedValue(@Nullable Variant value) {
    ServerNodeSupport.write(this, this, value, false, false, false);
  }
}
